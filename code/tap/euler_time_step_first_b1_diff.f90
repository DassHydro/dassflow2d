! Infiltrated depth over current time step (F^(n+1))
          arg1_diff = 2._rp*afn1*afn1_diff + 4._rp*bfn1_diff
          arg1 = afn1**2._rp + 4._rp*bfn1
          temp1 = SQRT(arg1)
          IF (arg1 .EQ. 0.0) THEN
            result1_diff = 0.0_8
          ELSE
            result1_diff = arg1_diff/(2.0*temp1)
          END IF
          result1 = temp1
          fn1_diff = (afn1_diff+result1_diff)/2._rp
          fn1 = (afn1+result1)/2._rp
          h_infil_diff = dof_diff%h(i) + dof_diff%infil(i) - fn1_diff
          h_infil = dof%h(i) + dof%infil(i) - fn1
          IF (h_infil .LT. 0._rp) THEN
! If more than the available water depth should be infiltrated, infiltrate only the total depth (h^n + r * Dt)
            fn1_diff = dof_diff%h(i) + dof_diff%infil(i)
            fn1 = dof%h(i) + dof%infil(i)
            h_infil = 0._rp
            h_infil_diff = 0.0_8
          END IF
! Pass h^(n+1) to dof%h (h^n)
          dof_diff%h(i) = h_infil_diff
          dof%h(i) = h_infil
! Pass F^(n+1) to dof%infil (F^n)
          dof_diff%infil(i) = fn1_diff
          dof%infil(i) = fn1
        END IF
      END IF
    END IF
    IF (dof%h(i) .LE. heps) THEN
      dof_diff%u(i) = 0.0_8
      dof%u(i) = 0._rp
      dof_diff%v(i) = 0.0_8
      dof%v(i) = 0._rp
    ELSE
      temp1 = dt*mesh%cell(i)%invsurf
      temp0 = tflux(2, i)/sporosity%phi(sporosity%land(i))
      temp = (h*u-temp1*temp0)/dof%h(i)
      dof_diff%u(i) = (u*h_diff+h*u_diff-temp1*(tflux_diff(2, i)-temp0*&
&       sporosity_diff%phi(sporosity%land(i)))/sporosity%phi(sporosity%&
&       land(i))-temp*dof_diff%h(i))/dof%h(i)
      dof%u(i) = temp
      temp1 = dt*mesh%cell(i)%invsurf
      temp0 = tflux(3, i)/sporosity%phi(sporosity%land(i))
      temp = (h*v-temp1*temp0)/dof%h(i)
      dof_diff%v(i) = (v*h_diff+h*v_diff-temp1*(tflux_diff(3, i)-temp0*&
&       sporosity_diff%phi(sporosity%land(i)))/sporosity%phi(sporosity%&
&       land(i))-temp*dof_diff%h(i))/dof%h(i)
      dof%v(i) = temp
      IF (friction .EQ. 1) THEN
        arg1_diff = 2*dof%u(i)*dof_diff%u(i) + 2*dof%v(i)*dof_diff%v(i)
        arg1 = dof%u(i)**2 + dof%v(i)**2
        temp1 = SQRT(arg1)
        IF (arg1 .EQ. 0.0) THEN
          vel_diff = 0.0_8
        ELSE
          vel_diff = arg1_diff/(2.0*temp1)
        END IF
        vel = temp1
        temp1 = 4._rp*dt*g
        temp0 = manning_beta(land(i))
        temp = dof%h(i)
        temp2 = temp**temp0
        temp3 = manning(land(i))*manning(land(i))
        IF (temp .LE. 0.0 .AND. (temp0 .EQ. 0.0 .OR. temp0 .NE. INT(&
&           temp0))) THEN
          temp_diff = 0.0_8
        ELSE IF (temp .LE. 0.0) THEN
          temp_diff = temp0*temp**(temp0-1)*dof_diff%h(i)
        ELSE
          temp_diff = temp0*temp**(temp0-1)*dof_diff%h(i) + temp2*LOG(&
&           temp)*manning_beta_diff(land(i))
        END IF
        IF (dof%h(i) .LE. 0.0 .AND. (d4p3 .EQ. 0.0 .OR. d4p3 .NE. INT(&
&           d4p3))) THEN
          arg1_diff = temp1*(temp2**2*(vel*2*manning(land(i))*&
&           manning_diff(land(i))+temp3*vel_diff)+temp3*vel*2*temp2*&
&           temp_diff)
        ELSE
          arg1_diff = d4p3*dof%h(i)**(d4p3-1)*dof_diff%h(i) + temp1*(&
&           temp2**2*(vel*2*manning(land(i))*manning_diff(land(i))+temp3&
&           *vel_diff)+temp3*vel*2*temp2*temp_diff)
        END IF
        arg1 = dof%h(i)**d4p3 + temp1*(temp3*vel*(temp2*temp2))
        temp3 = SQRT(arg1)
        IF (arg1 .EQ. 0.0) THEN
          result1_diff = 0.0_8
        ELSE
          result1_diff = arg1_diff/(2.0*temp3)
        END IF
        result1 = temp3
        IF (dof%h(i) .LE. 0.0 .AND. (d2p3 .EQ. 0.0 .OR. d2p3 .NE. INT(&
&           d2p3))) THEN
          sfl_diff = result1_diff
        ELSE
          sfl_diff = d2p3*dof%h(i)**(d2p3-1)*dof_diff%h(i) + &
&           result1_diff
        END IF
        sfl = dof%h(i)**d2p3 + result1
        temp2 = dof%h(i)**d2p3/sfl
        IF (dof%h(i) .LE. 0.0 .AND. (d2p3 .EQ. 0.0 .OR. d2p3 .NE. INT(&
&           d2p3))) THEN
          temp_diff0 = 0.0_8
        ELSE
          temp_diff0 = d2p3*dof%h(i)**(d2p3-1)*dof_diff%h(i)
        END IF
        sfl_diff = 2._rp*(temp_diff0-temp2*sfl_diff)/sfl
        sfl = 2._rp*temp2
      ELSE IF (friction .EQ. 2) THEN
        sfl_diff = -(dt*manning_diff(land(i)))
        sfl = one - dt*manning(land(i))
      ELSE
        sfl = 1._rp
        sfl_diff = 0.0_8
      END IF
      dof_diff%u(i) = sfl*dof_diff%u(i) + dof%u(i)*sfl_diff
      dof%u(i) = dof%u(i)*sfl
      dof_diff%v(i) = sfl*dof_diff%v(i) + dof%v(i)*sfl_diff
      dof%v(i) = dof%v(i)*sfl
    END IF
  END DO
  CALL COM_DOF(dof, mesh)
! Required MPI Communication due to inverse variable dependency
  CALL COM_VAR_R(bathy_cell, mesh)

CONTAINS
