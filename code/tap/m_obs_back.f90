              IF (branch .EQ. 0) THEN
                CALL POPREAL8(abs0)
                xsshape_back(1)%hmax = xsshape_back(1)%hmax - abs0_back
              ELSE
                CALL POPREAL8(abs0)
                xsshape_back(1)%hmax = xsshape_back(1)%hmax + abs0_back
              END IF
            END IF
          END DO
        ELSE IF (branch .EQ. 1) THEN
          DO ie=mesh%nc,1,-1
            CALL POPCONTROL1B(branch)
            IF (branch .EQ. 0) THEN
              bathy_cell_back(ie) = bathy_cell_back(ie) + &
&               bathy_temp_back(ie)
              min4_back = -bathy_temp_back(ie)
              mesh_back%cell(ie)%grav%y = mesh_back%cell(ie)%grav%y - &
&               slope_y(1)*bathy_temp_back(ie)
              mesh_back%cell(ie)%grav%x = mesh_back%cell(ie)%grav%x - &
&               slope_x(1)*bathy_temp_back(ie)
              bathy_temp_back(ie) = 0.0_8
              CALL POPCONTROL1B(branch)
              IF (branch .EQ. 0) THEN
                y4_back = min4_back
              ELSE
                y4_back = 0.0_8
              END IF
              temp1 = abs11/(xsshape(1)%xright-xsshape(1)%xcenter)
              temp0 = temp1**abs19
              abs3_back = -((1-temp0)*y4_back)
              IF (temp1 .LE. 0.0 .AND. (abs19 .EQ. 0.0 .OR. abs19 .NE. &
&                 INT(abs19))) THEN
                temp_back0 = 0.0_8
              ELSE
