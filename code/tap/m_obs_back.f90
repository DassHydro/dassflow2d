              IF (branch .EQ. 0) THEN
                CALL POPREAL8(abs18)
                xsshape_back(1)%s = xsshape_back(1)%s + abs18_back
              ELSE
                CALL POPREAL8(abs18)
                xsshape_back(1)%s = xsshape_back(1)%s - abs18_back
              END IF
              CALL POPCONTROL1B(branch)
              IF (branch .EQ. 0) THEN
                CALL POPREAL8(abs10)
                xsshape_back(1)%xcenter = xsshape_back(1)%xcenter + &
&                 abs10_back
                mesh_back%cell(ie)%grav%y = mesh_back%cell(ie)%grav%y - &
&                 abs10_back
              ELSE
                CALL POPREAL8(abs10)
                mesh_back%cell(ie)%grav%y = mesh_back%cell(ie)%grav%y + &
