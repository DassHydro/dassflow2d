&                 abs8_back
                mesh_back%cell(ie)%grav%x = mesh_back%cell(ie)%grav%x - &
&                 abs8_back
              ELSE
                CALL POPREAL8(abs8)
                mesh_back%cell(ie)%grav%x = mesh_back%cell(ie)%grav%x + &
&                 abs8_back
                xsshape_back(1)%xcenter = xsshape_back(1)%xcenter - &
&                 abs8_back
              END IF
